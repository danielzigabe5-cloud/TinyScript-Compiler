import argparse
from pathlib import Path
from lexer import Lexer
from lexer import LexerError
from parser import Parser
from parser import ParserError
from semantic import SemanticAnalyzer
from semantic import SemanticError
from compiler import Compiler
from vm import VirtualMachine
from vm import VMError

def compile_source(source):
    tokens=Lexer(source).tokenize()
    tree=Parser(tokens).parse()
    SemanticAnalyzer().analyze(tree)
    return Compiler().compile(tree),tokens

def format_bytecode(code):
    return "".join(
        f"{i:04} {op} {arg if arg is not None else ''}\n"
        for i,(op,arg) in enumerate(code)
    )

def main():
    ap=argparse.ArgumentParser(description="TinyScript compiler and bytecode virtual machine")
    ap.add_argument("file",help="TinyScript source file")
    ap.add_argument("--tokens",action="store_true")
    ap.add_argument("--bytecode",action="store_true")
    ap.add_argument("--save-bytecode",nargs="?",const="",metavar="PATH",
                    help="save generated instructions to a .bc file (default: source filename with .bc extension)")
    args=ap.parse_args()
    try:
        source_path=Path(args.file)
        source=source_path.read_text(encoding="utf-8")
        code,tokens=compile_source(source)
        if args.save_bytecode is not None:
            output_path=Path(args.save_bytecode) if args.save_bytecode else source_path.with_suffix(".bc")
            if output_path.suffix.lower()!=".bc":
                ap.error("--save-bytecode output path must use the .bc extension")
            output_path.write_text(format_bytecode(code),encoding="utf-8")
        if args.tokens:
            for t in tokens:print(t)
        else:
            if args.bytecode:
                print("=== GENERATED BYTECODE ===")
                print(format_bytecode(code),end="")
                print("=== PROGRAM OUTPUT ===")
            VirtualMachine(code).run()
    except LexerError as e:
        print(f"Lexical error: {e}")
        raise SystemExit(1)
    except ParserError as e:
        print(f"Syntax error: {e}")
        raise SystemExit(1)
    except SemanticError as e:
        print(f"Semantic error: {e}")
        raise SystemExit(1)
    except VMError as e:
        print(f"Runtime error: {e}")
        raise SystemExit(1)
    except OSError as e:
        print(f"File error: {e}")
        raise SystemExit(1)
if __name__=="__main__":main()
